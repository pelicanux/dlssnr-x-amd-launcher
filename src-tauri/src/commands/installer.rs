use crate::commands::analyzer::scan_directory_for_exe;

#[derive(serde::Serialize)]
pub struct GameInstallationDetails {
    status: String,
    installed_dll: Option<String>,
}

fn details_in_directory(dir: &std::path::Path) -> GameInstallationDetails {
    let has = |names: &[&str]| names.iter().any(|name| dir.join(name).is_file());
    // Proxy DLL names alone are not evidence: games, DXVK and other tools ship them too.
    let optiscaler = has(&["OptiScaler.dll", "OptiScaler.ini", "dlssnr_core.dll", "nvngx.dll_dlssnr.dll", "nvngx_dlssnr.dll"]);
    let addon = has(&["dlssnr_amd.addon64", "dlssnr_amd.addon32"]);
    let manifest = dir.join("dlssnr-amd-install.txt").is_file()
        && dir.join("dlssnr-amd/dlssnr.bin").is_file();
    let proxy_names = ["vulkan-1.dll", "winevulkan.dll", "dxgi.dll", "d3d9.dll", "winmm.dll", "version.dll", "d3d12.dll", "d3d11.dll", "dinput8.dll", "ReShade64.dll", "ReShade32.dll", "OptiScaler.dll"];
    // Prefer the loader recorded by the installer over similarly named original game DLLs.
    use std::io::Read;
    let mut recorded_files = String::new();
    if let Ok(file) = std::fs::File::open(dir.join("dlssnr-amd-install.txt")) {
        let _ = file.take(64 * 1024).read_to_string(&mut recorded_files);
    }
    let proxy = proxy_names.iter().find(|name| dir.join(name).is_file()
        && recorded_files.lines().any(|line| line.trim() == **name))
        .or_else(|| proxy_names.iter().find(|name| dir.join(name).is_file()));
    let status = if proxy.is_none() || !(optiscaler || addon || manifest) {
        "Não Instalado"
    } else if optiscaler {
        "OptiScaler"
    } else if matches!(proxy.copied(), Some("vulkan-1.dll" | "winevulkan.dll")) {
        "Vulkan/DX9"
    } else {
        "ReShade"
    };
    let installed_dll = if status == "Não Instalado" { None } else { proxy.map(|name| (*name).to_string()) };
    GameInstallationDetails { status: status.to_string(), installed_dll }
}

pub(crate) fn installed_mod_directory(base_dir: &std::path::Path) -> Option<std::path::PathBuf> {
    if details_in_directory(base_dir).status != "Não Instalado" { return Some(base_dir.to_path_buf()); }
    let exe = scan_directory_for_exe(base_dir)?;
    let dir = exe.parent()?;
    if details_in_directory(dir).status != "Não Instalado" { Some(dir.to_path_buf()) } else { None }
}

fn installation_details(game_dir: &str) -> GameInstallationDetails {
    let base_dir = std::path::Path::new(game_dir);
    if !base_dir.exists() {
        return GameInstallationDetails { status: "Não Instalado".to_string(), installed_dll: None };
    }
    let root_details = details_in_directory(base_dir);
    // install.sh writes into the selected folder, even when the largest EXE is nested.
    // The manifest/add-on/core files identify that folder without another directory walk.
    let root_has_mod = ["dlssnr-amd-install.txt", "dlssnr_core.dll", "OptiScaler.ini", "dlssnr_amd.addon64", "dlssnr_amd.addon32", "ReShade.ini"].iter().any(|name| base_dir.join(name).is_file());
    if root_has_mod && root_details.status != "Não Instalado" { return root_details; }

    // Retain detection for existing installations next to a nested game executable.
    let exe_path = scan_directory_for_exe(base_dir);
    if let Some(dir) = exe_path.as_ref().and_then(|exe| exe.parent()) {
        if dir != base_dir {
            let nested_details = details_in_directory(dir);
            if nested_details.status != "Não Instalado" { return nested_details; }
        }
    }
    root_details
}

#[tauri::command]
pub async fn get_game_installation_details(game_dir: String) -> Result<GameInstallationDetails, String> {
    tauri::async_runtime::spawn_blocking(move || installation_details(&game_dir))
        .await.map_err(|error| error.to_string())
}

#[tauri::command]
pub async fn check_game_installation(game_dir: String) -> Result<String, String> {
    Ok(get_game_installation_details(game_dir).await?.status)
}

#[tauri::command]
pub async fn get_installed_dll(game_dir: String) -> Result<Option<String>, String> {
    Ok(get_game_installation_details(game_dir).await?.installed_dll)
}

#[tauri::command]
pub fn extract_dll(
    app: AppHandle,
    dll_path: String,
    gpu_arch: String,
    bitness: String,
) -> Result<String, String> {
    use std::fs;
    let base_dir = get_backend_dir(&app)?;
    
    // Default to putting it in the backend folder
    let dest_dir = base_dir.join(&gpu_arch).join(&bitness).join("dlssnr-amd");
    if !dest_dir.exists() {
        fs::create_dir_all(&dest_dir).map_err(|e| e.to_string())?;
    }
    
    let dest_path = dest_dir.join("dlssnr.bin");
    fs::copy(&dll_path, &dest_path).map_err(|e| format!("Failed to copy DLL to bin: {}", e))?;
    
    Ok(dest_path.to_string_lossy().to_string())
}

#[tauri::command]
pub async fn extract_dll_wizard(
    app: AppHandle,
    dll_path: String,
    gpu_arch: String,
) -> Result<String, String> {
    use std::fs;
    use std::env;
    use tauri::Manager;
    use crate::core::script_runner;

    let base_dir = app.path().config_dir().map_err(|e| e.to_string())?.join("dlssnr-x-amd");

    if !base_dir.exists() {
        fs::create_dir_all(&base_dir).map_err(|e| e.to_string())?;
    }

    let dest_path = base_dir.join("dlssnr.bin");

    let app_config_backends = get_backend_dir(&app)?;
    // We'll use 64-bit backend as default for extraction
    let resource_path = app_config_backends.join(&gpu_arch).join("64");

    if !resource_path.exists() {
        return Err("Backend não encontrado! Certifique-se de baixar primeiro.".to_string());
    }

    let temp_game_dir = env::temp_dir().join(format!("dummy-game-{}", uuid::Uuid::new_v4()));
    fs::create_dir_all(&temp_game_dir).map_err(|e| e.to_string())?;

    // Run the heavy I/O work in a blocking thread pool to avoid freezing the UI
    let resource_path_clone = resource_path.clone();
    let temp_game_dir_clone = temp_game_dir.clone();
    let dll_path_clone = dll_path.clone();

    let res = tokio::task::spawn_blocking(move || {
        script_runner::execute_standalone_install(
            &resource_path_clone,
            &temp_game_dir_clone.to_string_lossy(),
            "reshade",
            Some(&dll_path_clone),
            None,
            "Insert",
        )
    }).await.map_err(|e| format!("Task error: {}", e))?;

    let _ = fs::remove_dir_all(&temp_game_dir);

    if res.is_err() {
        return Err(res.unwrap_err());
    }

    // After standalone install, the bin should be cached at resource_path/dlssnr-amd/dlssnr.bin
    let cached_bin = resource_path.join("dlssnr-amd/dlssnr.bin");
    if cached_bin.exists() {
        fs::copy(&cached_bin, &dest_path).map_err(|e| format!("Falha ao copiar bin final: {}", e))?;
        Ok(dest_path.to_string_lossy().to_string())
    } else {
        Err("A extração falhou: dlssnr.bin não foi gerado pelo backend.".to_string())
    }
}


#[cfg(test)]
mod installation_details_tests {
    use super::*;
    #[test]
    fn recognizes_all_routes_in_selected_folder_with_nested_executable() {
        for (marker, proxy, expected) in [
            ("dlssnr_core.dll", "dxgi.dll", "OptiScaler"),
            ("dlssnr_amd.addon64", "dxgi.dll", "ReShade"),
            ("dlssnr_amd.addon32", "dxgi.dll", "ReShade"),
            ("dlssnr_amd.addon64", "winevulkan.dll", "Vulkan/DX9"),
            ("dlssnr_amd.addon32", "vulkan-1.dll", "Vulkan/DX9"),
            ("dlssnr_amd.addon32", "d3d9.dll", "ReShade"),
        ] {
            let root = std::env::temp_dir().join(format!("dlssnr-route-test-{}", uuid::Uuid::new_v4()));
            let nested = root.join("game/Binaries/Win64");
            std::fs::create_dir_all(&nested).unwrap();
            std::fs::write(nested.join("game.exe"), b"executable").unwrap();
            std::fs::write(root.join(marker), b"mod").unwrap();
            std::fs::write(root.join(proxy), b"proxy").unwrap();
            std::fs::write(root.join("dlssnr-amd-install.txt"), proxy).unwrap();
            let installed = installation_details(root.to_str().unwrap());
            assert_eq!(installed.status, expected);
            assert_eq!(installed.installed_dll.as_deref(), Some(proxy));
            std::fs::remove_file(root.join(marker)).unwrap();
            std::fs::remove_file(root.join(proxy)).unwrap();
            std::fs::remove_file(root.join("dlssnr-amd-install.txt")).unwrap();
            let removed = installation_details(root.to_str().unwrap());
            assert_eq!(removed.status, "Não Instalado");
            assert_eq!(removed.installed_dll, None);
            std::fs::remove_dir_all(root).unwrap();
        }
    }
    #[test]
    fn generic_game_dlls_and_stale_configs_do_not_identify_a_mod() {
        let root = std::env::temp_dir().join(format!("dlssnr-unmodified-test-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&root).unwrap();
        for name in ["dxgi.dll", "d3d9.dll", "nvngx.dll", "vulkan-1.dll", "winevulkan.dll", "ReShade64.dll", "ReShade.ini", "dlssnr-amd-install.txt"] {
            std::fs::write(root.join(name), b"game component").unwrap();
            let details = installation_details(root.to_str().unwrap());
            assert_eq!(details.status, "Não Instalado", "false positive from {name}");
            assert_eq!(details.installed_dll, None);
        }
        std::fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn manifest_loader_takes_precedence_over_original_game_dlls() {
        let root = std::env::temp_dir().join(format!("dlssnr-loader-test-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&root).unwrap();
        for name in ["vulkan-1.dll", "dxgi.dll", "dlssnr_amd.addon64"] {
            std::fs::write(root.join(name), b"component").unwrap();
        }
        std::fs::write(root.join("dlssnr-amd-install.txt"), "dxgi.dll\ndlssnr_amd.addon64\n").unwrap();
        let details = installation_details(root.to_str().unwrap());
        assert_eq!(details.status, "ReShade");
        assert_eq!(details.installed_dll.as_deref(), Some("dxgi.dll"));
        std::fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn addon_without_loader_is_not_a_complete_installation() {
        let root = std::env::temp_dir().join(format!("dlssnr-partial-test-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(root.join("dlssnr_amd.addon64"), b"mod").unwrap();
        assert_eq!(installation_details(root.to_str().unwrap()).status, "Não Instalado");
        std::fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn finds_mod_and_proxy_together() {
        let root = std::env::temp_dir().join(format!("dlssnr-details-test-{}", uuid::Uuid::new_v4()));
        let game = root.join("bin");
        std::fs::create_dir_all(&game).unwrap();
        std::fs::write(game.join("game.exe"), b"example").unwrap();
        std::fs::write(game.join("OptiScaler.dll"), b"example").unwrap();
        std::fs::write(game.join("dxgi.dll"), b"example").unwrap();
        let details = installation_details(root.to_str().unwrap());
        assert_eq!(details.status, "OptiScaler");
        assert_eq!(details.installed_dll.as_deref(), Some("dxgi.dll"));
        std::fs::remove_dir_all(&root).unwrap();
        let absent = installation_details(root.to_str().unwrap());
        assert_eq!(absent.status, "Não Instalado");
        assert_eq!(absent.installed_dll, None);
    }
}
